// Bundles the files the server reads while handling requests (blog MDX
// sources and the Open Graph font) into a module, because Cloudflare Workers
// have no filesystem at request time. Runs on install, before `next dev` and
// before `next build`; the output is git-ignored. Restart `pnpm dev` after
// changing a post's frontmatter.
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const blogDirectory = path.join(root, "content/blog");
const outFile = path.join(root, "shared/lib/generated/serverContent.ts");

const files = (await readdir(blogDirectory))
  .filter((file) => file.endsWith(".mdx"))
  .sort();
const blogPostSources = await Promise.all(
  files.map(async (file) => ({
    slug: file.slice(0, -4),
    source: await readFile(path.join(blogDirectory, file), "utf8"),
  }))
);
const blogExampleSource = await readFile(
  path.join(root, "content/blog-examples/content.mdx"),
  "utf8"
);
const geistRegular = await readFile(
  path.join(root, "node_modules/geist/dist/fonts/geist-sans/Geist-Regular.ttf")
);

await mkdir(path.dirname(outFile), { recursive: true });
await writeFile(
  outFile,
  [
    "// Generated by scripts/generate-server-content.mjs. Do not edit.",
    `export const blogPostSources: readonly { slug: string; source: string }[] = ${JSON.stringify(blogPostSources)};`,
    `export const blogExampleSource: string = ${JSON.stringify(blogExampleSource)};`,
    `export const geistRegularBase64: string = ${JSON.stringify(geistRegular.toString("base64"))};`,
    "",
  ].join("\n")
);
console.log(
  `[ServerContent] bundled ${blogPostSources.length} posts into ${path.relative(root, outFile)}`
);
